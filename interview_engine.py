"""
interview_engine.py

The actual interview agent. One InterviewSession is created per
sessionId on the first request (which must include `candidate`), and
every subsequent request with `message` advances that session's state
machine by one turn until the plan is exhausted, at which point
structured feedback is generated and `done: true` is returned.

Design of the interview flow
-----------------------------
1. INTRO           - greet the candidate by name/role, set expectations
2. STRENGTH probes - verify claimed strengths aren't just "checkbox passes"
3. GAP probes      - dig into skipped / failed / high-attempt / untouched
                      curriculum areas to see how the candidate reasons
                      about things they struggled with
4. DESIGN question - one open-ended, role-relevant system design prompt
                      tying multiple modules together (RAG + agents +
                      deployment), to see holistic thinking
5. CLOSING         - thank the candidate, then synthesize feedback from
                      the full transcript + their original signals

Each question is generated by the LLM when available (grounded in the
specific topic + the candidate's own attempt history), with a
deterministic template fallback so the flow never breaks if no LLM
credentials are configured.
"""

import random
from typing import Any, Dict, List, Optional

from curriculum_analysis import build_topic_profile
from llm_client import generate_json, generate_text, llm_available
from models import Feedback

# In-memory session store. Fine for a hackathon-scoped demo; the spec
# explicitly does not require persistence beyond the life of an interview.
SESSIONS: Dict[str, "InterviewSession"] = {}

MAX_STRENGTH_QS = 3
MAX_GAP_QS = 3


class InterviewSession:
    def __init__(self, session_id: str, candidate: Dict[str, Any]):
        self.session_id = session_id
        self.candidate = candidate
        self.profile = build_topic_profile(candidate)
        self.plan: List[Dict[str, Any]] = self._build_plan()
        self.index = -1  # -1 = intro not yet sent
        self.qa_log: List[Dict[str, Any]] = []
        self.done = False

    # ------------------------------------------------------------------
    # Plan construction
    # ------------------------------------------------------------------
    def _build_plan(self) -> List[Dict[str, Any]]:
        plan: List[Dict[str, Any]] = []

        strong = list(self.profile["strong"])
        random.shuffle(strong)
        for topic in strong[:MAX_STRENGTH_QS]:
            plan.append({"type": "strength", "topic": topic})

        gap_pool = list(self.profile["skipped"]) + list(self.profile["weak"]) + list(
            self.profile["unattempted"]
        )
        random.shuffle(gap_pool)
        for topic in gap_pool[:MAX_GAP_QS]:
            plan.append({"type": "gap", "topic": topic})

        plan.append({"type": "design", "topic": None})
        return plan

    # ------------------------------------------------------------------
    # Turn handling
    # ------------------------------------------------------------------
    def start(self) -> str:
        member = self.profile["member"]
        name = member.get("name", "there")
        role = member.get("jobRole", "the role")

        text = generate_text(
            system=(
                "You are a warm, sharp technical interviewer for an AI Engineering "
                "bootcamp graduate program. Write a short (2-4 sentence) welcome "
                "message that greets the candidate by name, references their target "
                "role, and sets expectations: this is a conversational technical "
                "interview based on their actual coursework, and it ends with "
                "structured feedback. Do not ask a question yet."
            ),
            user=f"Candidate: {name}, applying for: {role}, years experience: "
            f"{member.get('yearsExperience', 'n/a')}.",
        )
        if not text:
            text = (
                f"Welcome, {name}! I'll be conducting your technical interview today "
                f"for the {role} track. We'll walk through a few areas from your "
                f"cohort work, including some you nailed and a couple you found "
                f"tougher, then wrap up with a short design question. At the end "
                f"I'll give you structured feedback. Ready when you are."
            )

        self.index = 0
        return text + "\n\n" + self._question_intro_lead_in()

    def _question_intro_lead_in(self) -> str:
        return self._render_question(self.plan[0])

    def handle_message(self, message: str) -> Dict[str, Any]:
        """Log the answer to the current question, then either ask the
        next question or wrap up with feedback."""
        if self.index >= 0 and self.index < len(self.plan):
            current = self.plan[self.index]
            self.qa_log.append(
                {
                    "type": current["type"],
                    "topic": current["topic"],
                    "question": current.get("_rendered_question", ""),
                    "answer": message,
                }
            )

        self.index += 1

        if self.index < len(self.plan):
            next_q = self.plan[self.index]
            ack = self._acknowledge(message, self.qa_log[-1] if self.qa_log else None)
            question_text = self._render_question(next_q)
            reply = (ack + "\n\n" + question_text).strip()
            return {"reply": reply, "done": False, "feedback": None}

        # Plan exhausted -> close out and produce feedback
        self.done = True
        closing = (
            "That covers everything I wanted to dig into today. Thanks for "
            "walking me through your reasoning — give me a moment to put together "
            "your feedback."
        )
        feedback = self._generate_feedback()
        return {"reply": "Interview completed. " + closing, "done": True, "feedback": feedback}

    # ------------------------------------------------------------------
    # Question generation
    # ------------------------------------------------------------------
    def _render_question(self, plan_item: Dict[str, Any]) -> str:
        qtype = plan_item["type"]
        topic = plan_item["topic"]
        role = self.profile["member"].get("jobRole", "this role")

        if qtype == "strength":
            question = self._gen_strength_question(topic, role)
        elif qtype == "gap":
            question = self._gen_gap_question(topic, role)
        else:
            question = self._gen_design_question(role)

        plan_item["_rendered_question"] = question
        return question

    def _gen_strength_question(self, topic: Dict[str, Any], role: str) -> str:
        text = generate_text(
            system=(
                "You are a technical interviewer. The candidate passed this "
                "curriculum topic quickly/cleanly, suggesting real strength. "
                "Ask ONE probing question (1-2 sentences) that verifies depth, "
                "not just recall — e.g. ask them to explain a tradeoff, a "
                "failure mode, or how they'd extend/scale it. Do not restate "
                "these instructions."
            ),
            user=f"Role: {role}. Topic: {topic['title']} (module: {topic['module']}, "
            f"tools: {', '.join(topic.get('tools', [])) or 'n/a'}). "
            f"Attempts to pass: {topic.get('attempts', 1)}.",
        )
        if text:
            return text
        return (
            f"You moved through **{topic['title']}** quickly. Walk me through a "
            f"tradeoff or failure mode you'd watch for there, and how you'd handle "
            f"it in production."
        )

    def _gen_gap_question(self, topic: Dict[str, Any], role: str) -> str:
        reason = (
            "skipped it entirely"
            if topic in self.profile["skipped"]
            else "never attempted it"
            if topic in self.profile["unattempted"]
            else f"needed several attempts ({topic.get('attempts', '?')}) to pass"
        )
        text = generate_text(
            system=(
                "You are a technical interviewer. The candidate struggled with, "
                "skipped, or never attempted this curriculum topic. Ask ONE "
                "supportive but genuinely probing question (1-2 sentences) that "
                "checks their current conceptual understanding of the topic — "
                "frame it as curiosity, not a gotcha. Do not restate these "
                "instructions."
            ),
            user=f"Role: {role}. Topic: {topic['title']} (module: {topic['module']}). "
            f"Context: candidate {reason}.",
        )
        if text:
            return text
        return (
            f"I noticed **{topic['title']}** was a tougher spot for you. In your own "
            f"words, what's the core idea there, and where have you seen it matter "
            f"in a real project?"
        )

    def _gen_design_question(self, role: str) -> str:
        text = generate_text(
            system=(
                "You are a technical interviewer closing out a systems-design "
                "portion of an interview. Ask ONE open-ended system design "
                "question (2-3 sentences) tailored to the candidate's target "
                "role that requires them to connect retrieval, LLM reasoning, "
                "and production concerns (reliability, cost, or security). Do "
                "not restate these instructions."
            ),
            user=f"Candidate role: {role}.",
        )
        if text:
            return text
        return (
            f"Last one: imagine you're designing a production RAG chatbot for a "
            f"regulated domain, in your role as a {role}. Walk me through how "
            f"you'd architect retrieval, keep answers grounded, and handle "
            f"failures or cost blowups at scale."
        )

    def _acknowledge(self, answer: str, qa_entry: Optional[Dict[str, Any]]) -> str:
        text = generate_text(
            system=(
                "You are a technical interviewer. In ONE short sentence, briefly "
                "and specifically acknowledge the candidate's previous answer "
                "(no generic 'great answer' filler — reference something "
                "concrete they said) before moving on. Do not ask the next "
                "question here."
            ),
            user=f"Candidate answer: {answer}",
            max_tokens=100,
        )
        if text:
            return text
        return "Got it, thanks for walking me through that."

    # ------------------------------------------------------------------
    # Feedback synthesis
    # ------------------------------------------------------------------
    def _generate_feedback(self) -> Feedback:
        transcript = "\n\n".join(
            f"[{qa['type'].upper()} | {qa['topic']['title'] if qa['topic'] else 'System Design'}]\n"
            f"Q: {qa['question']}\nA: {qa['answer']}"
            for qa in self.qa_log
        )
        member = self.profile["member"]
        signals = self.profile["signals"]

        data = generate_json(
            system=(
                "You are a technical interviewer writing final structured "
                "feedback for a hiring pipeline. Base your assessment ONLY on "
                "the interview transcript provided (their live answers), using "
                "the coursework signals only as light supporting context. "
                'Return JSON with exactly these keys: "summary" (2-3 sentence '
                'string), "strengths" (array of concise strings), "gaps" '
                '(array of concise strings), "next" (array of concise, '
                "actionable next-step strings for this candidate)."
            ),
            user=(
                f"Candidate: {member.get('name')}, role: {member.get('jobRole')}, "
                f"experience: {member.get('yearsExperience')} yrs.\n"
                f"Coursework signals: {signals}\n\n"
                f"Interview transcript:\n{transcript}"
            ),
        )

        if data and all(k in data for k in ("summary", "strengths", "gaps", "next")):
            try:
                return Feedback(
                    summary=str(data["summary"]),
                    strengths=[str(x) for x in data["strengths"]],
                    gaps=[str(x) for x in data["gaps"]],
                    next=[str(x) for x in data["next"]],
                )
            except Exception:
                pass

        return self._fallback_feedback()

    def _fallback_feedback(self) -> Feedback:
        """Deterministic feedback built straight from the topic profile and
        transcript length, used when no LLM is configured."""
        member = self.profile["member"]
        strengths = [
            f"Demonstrated solid grasp of {t['title']}"
            for t in self.profile["strong"][:MAX_STRENGTH_QS]
        ] or ["Completed the interview and engaged with each topic raised."]

        gaps = []
        for t in self.profile["skipped"][:2]:
            gaps.append(f"Skipped {t['title']} during the program — worth revisiting")
        for t in self.profile["weak"][:2]:
            gaps.append(f"Needed multiple attempts on {t['title']}; understanding may be shallow")
        for t in self.profile["unattempted"][:1]:
            gaps.append(f"No record of engaging with {t['title']}")
        if not gaps:
            gaps = ["No major curriculum gaps identified; probe deeper in a follow-up round"]

        next_steps = [
            f"Follow up with a hands-on exercise covering {self.profile['weak'][0]['title']}"
            if self.profile["weak"]
            else "Proceed to a role-specific take-home or pairing session",
            "Validate system design reasoning with a whiteboard round",
        ]

        summary = (
            f"{member.get('name', 'The candidate')} completed a {len(self.qa_log)}-question "
            f"interview spanning strengths from their coursework, previously skipped or "
            f"difficult topics, and one system design scenario for the "
            f"{member.get('jobRole', 'target')} role."
        )

        return Feedback(summary=summary, strengths=strengths, gaps=gaps, next=next_steps)


def get_or_create_session(session_id: str, candidate: Optional[Dict[str, Any]]) -> InterviewSession:
    if session_id in SESSIONS:
        return SESSIONS[session_id]
    if candidate is None:
        raise ValueError("New session requires a 'candidate' object on the first request.")
    session = InterviewSession(session_id, candidate)
    SESSIONS[session_id] = session
    return session